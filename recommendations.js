  function weaponOptions(character,{custom=false}={}){
    const c=root.GDATA.characters.find(c=>c.key===character),record=data.characters[character];
    if(!c)return [['','请选择武器']];
    const available=root.GDATA.weapons.filter(w=>w.type===c.weapon).sort((a,b)=>b.star-a.star);
    const byName=new Map(available.map(w=>[w.name,w])),used=new Set(),options=[['','请选择武器']];
    const label=name=>'★'+byName.get(name).star+' '+name+(data.weaponAliases[name]?'（'+data.weaponAliases[name]+'）':'');
    const take=items=>items.filter(([name])=>byName.has(name)&&!used.has(name)&&used.add(name));
    const signatures=take((record?.signatures||[]).map(w=>[w.name,label(w.name)+(w.relation==='signature'?' · 专武':' · 定制/配套')]));
    if(signatures.length)options.push(group('专武 / 定制配套',signatures));
    const recommended=take((record?.weapons||[]).filter(n=>byName.has(n)).map(n=>[n,label(n)]));
    if(recommended.length)options.push(group('常用推荐武器',recommended));
    const others=take(available.map(w=>[w.name,label(w.name)]));
    if(others.length)options.push(group('其他武器 · 按星级',others));
    if(custom)options.push(['custom','自定义武器']);
    return options;
  }
